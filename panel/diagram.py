"""
The data model as diagrams, drawn from the database itself (information_schema), so they match what exists.

    python -m panel.diagram          # writes docs/model_diagram.md (Mermaid, rendered by GitHub)

One entity-relationship diagram per subject area, showing each table with its keys (primary and foreign) and
every foreign key as a relation. A table is drawn in the area of its schema; a relation to another area's
table is drawn too, so the connections between areas are visible.
"""
from collections import defaultdict
from pathlib import Path

from panel.load_db import connect

ROOT = Path(__file__).resolve().parent.parent
SCHEMAS = ["RelationsAndConclusions", "Physical_violence", "Cultural_violence", "GENDER_VIOLENCE", "Structural_Violence",
           "Education_Outcomes", "Student_Context", "Territorial_Context", "State_Action", "Research_Design"]


def main():
    db = connect()
    cur = db.cursor()
    inlist = ", ".join(f"'{s.lower()}'" for s in SCHEMAS)
    cur.execute(f"""SELECT TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME, COLUMN_TYPE, COLUMN_KEY
                    FROM information_schema.COLUMNS WHERE LOWER(TABLE_SCHEMA) IN ({inlist})
                    AND TABLE_NAME NOT LIKE '\\_%' ORDER BY TABLE_SCHEMA, TABLE_NAME, ORDINAL_POSITION""")
    columns = defaultdict(list)
    for s, t, c, typ, key in cur.fetchall():
        columns[(s.lower(), t.lower())].append((c, typ, key))
    cur.execute(f"""SELECT TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME, REFERENCED_TABLE_SCHEMA, REFERENCED_TABLE_NAME
                    FROM information_schema.KEY_COLUMN_USAGE
                    WHERE REFERENCED_TABLE_NAME IS NOT NULL AND LOWER(TABLE_SCHEMA) IN ({inlist})""")
    fks = [(s.lower(), t.lower(), c, rs.lower(), rt.lower()) for s, t, c, rs, rt in cur.fetchall()]
    cur.execute(f"SELECT LOWER(TABLE_SCHEMA), LOWER(TABLE_NAME) FROM information_schema.TABLES "
                f"WHERE LOWER(TABLE_SCHEMA) IN ({inlist}) AND TABLE_TYPE = 'BASE TABLE'")
    tables = set(cur.fetchall())
    db.close()
    fk_cols = {(s, t, c) for s, t, c, _, _ in fks}
    real = {s.lower(): s for s in SCHEMAS}

    def entity(s, t):
        lines = [f"    {t} {{"]
        for c, typ, key in columns[(s, t)]:
            if key == "PRI" or (s, t, c) in fk_cols:
                kind = typ.split("(")[0].replace(" ", "_")
                mark = "PK" if key == "PRI" else "FK"
                if key == "PRI" and (s, t, c) in fk_cols:
                    mark = "PK, FK"
                lines.append(f"        {kind} {c} {mark}")
        lines.append("    }")
        return lines

    out = ["# Data model diagram", "",
           "Generated by `python -m panel.diagram` from the database: each table with its primary (PK) and foreign (FK)",
           "keys, and every foreign key as a relation. Tables of another area appear where they are referenced.", ""]
    for schema in SCHEMAS:
        s = schema.lower()
        own = sorted(t for (sc, t) in tables if sc == s)
        if not own:
            continue
        out += [f"## {schema}", "", f"{len(own)} tables.", "", "```mermaid", "erDiagram"]
        drawn = set()
        for t in own:
            out += entity(s, t)
            drawn.add((s, t))
        for fs, ft, c, rs, rt in fks:
            if fs == s and (rs, rt) not in drawn:
                out += [f"    {rt} {{", "    }"]
                drawn.add((rs, rt))
            if fs == s:
                out.append(f"    {rt} ||--o{{ {ft} : {c}")
        out += ["```", ""]
    path = ROOT / "docs" / "model_diagram.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {path}: {len(tables)} tables, {len(fks)} foreign keys")


if __name__ == "__main__":
    main()
